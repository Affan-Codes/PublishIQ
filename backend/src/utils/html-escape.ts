/**
 * Escapes unsafe characters in text strings before HTML interpolation
 * to prevent HTML/XSS injection attacks.
 */
export function escapeHtml(unsafe: string): string {
  return unsafe
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

export default escapeHtml;
